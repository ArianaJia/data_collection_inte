#ifndef TELEMETRY_UPDATES_H
#define TELEMETRY_UPDATES_H
#include <stdint.h>

/* Cache update identities, not value-change detection or wire field numbers.
 * Extra and CANC reserve one identity per independently received cache slot. */
typedef uint64_t TelemetryUpdates;
typedef enum {
    TELEMETRY_DRIVER_INPUTS, TELEMETRY_GPS_SPEED, TELEMETRY_POSITION,
    TELEMETRY_GPS_MOTION, TELEMETRY_CG_VELOCITY, TELEMETRY_GPS_STATUS,
    TELEMETRY_LAP_TIMING, TELEMETRY_STEERING_COMMAND, TELEMETRY_MODE_REQUEST,
    TELEMETRY_REGEN, TELEMETRY_PEDAL, TELEMETRY_ENERGY,
    TELEMETRY_MOTOR_TORQUE, TELEMETRY_MOTOR_DIAGNOSTIC, TELEMETRY_MOTOR_SPEED,
    TELEMETRY_MOTOR_TEMP, TELEMETRY_INVERTER_TEMP, TELEMETRY_IGBT_TEMP,
    TELEMETRY_AMK_STATUS, TELEMETRY_CANA_MOTOR,
    TELEMETRY_PACK, TELEMETRY_CELL_EXTREMA, TELEMETRY_TEMP_EXTREMA,
    TELEMETRY_BATTERY_STATUS, TELEMETRY_CELL_SUM, TELEMETRY_FAULT,
    TELEMETRY_IVT, TELEMETRY_MODULES,
    TELEMETRY_EXTRA_FIRST = 28,
    TELEMETRY_CANC_FIRST = 52,
    TELEMETRY_THERMAL = 62,
    TELEMETRY_GROUP_COUNT
} TelemetryGroup;
#define TELEMETRY_UPDATE(group) (UINT64_C(1) << (group))
#define TELEMETRY_EXTRA_UPDATE(index) TELEMETRY_UPDATE(TELEMETRY_EXTRA_FIRST + (index))
#define TELEMETRY_CANC_UPDATE(index) TELEMETRY_UPDATE(TELEMETRY_CANC_FIRST + (index))
#define TELEMETRY_ALL_UPDATES ((UINT64_C(1) << TELEMETRY_GROUP_COUNT) - 1U)
#endif
